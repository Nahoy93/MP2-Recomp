// Mario Party 2: Recompiled -- entry point.
//
// Registers the game with librecomp, hands ultramodern the platform callbacks
// (window, audio, input, RSP) and starts the runtime. The launcher that asks
// for the ROM, and the settings menu behind Escape, come from RecompFrontend
// (src/frontend.cpp).
//
// The structure follows Body Harvest: Recompiled (MIT), whose notes on the
// runtime's sharp edges saved a lot of guesswork; see THIRD_PARTY_NOTICES.md.

#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <string>
#include <system_error>
#include <vector>

#if defined(_WIN32)
#   define WIN32_LEAN_AND_MEAN
#   include <windows.h>
#   include <io.h>
#   include <timeapi.h>
#endif

// Our own main(); without this SDL renames it to SDL_main on Windows.
#define SDL_MAIN_HANDLED
#include <SDL.h>

#include "recomp.h"
#include <librecomp/game.hpp>
#include <ultramodern/ultramodern.hpp>

#include "mp2/game.h"
#include "mp2/frontend.h"
#include "rom_info.h"

#ifndef MP2_VERSION_MAJOR
#   define MP2_VERSION_MAJOR 0
#   define MP2_VERSION_MINOR 1
#   define MP2_VERSION_PATCH 0
#endif

// Generated by N64Recomp: the translated entry point of the cartridge.
extern "C" void recomp_entrypoint(uint8_t* rdram, recomp_context* ctx);

namespace mp2 {

std::filesystem::path settings_directory() {
    if (std::filesystem::exists("portable.txt")) {
        return std::filesystem::current_path();
    }
    std::filesystem::path root;
#if defined(_WIN32)
    if (const char* base = std::getenv("LOCALAPPDATA")) {
        root = base;
    }
#elif defined(__APPLE__)
    if (const char* home = std::getenv("HOME")) {
        root = std::filesystem::path{ home } / "Library" / "Application Support";
    }
#else
    if (const char* xdg = std::getenv("XDG_DATA_HOME"); xdg != nullptr && *xdg != '\0') {
        root = xdg;
    }
    else if (const char* home = std::getenv("HOME")) {
        root = std::filesystem::path{ home } / ".local" / "share";
    }
#endif
    if (root.empty()) {
        return std::filesystem::current_path();
    }
    return root / "mp2-recomp";
}

}  // namespace mp2

namespace {

std::filesystem::path executable_directory(const char* argv0) {
    std::error_code ec;
#if defined(_WIN32)
    wchar_t buffer[MAX_PATH * 4];
    const DWORD length = GetModuleFileNameW(nullptr, buffer, static_cast<DWORD>(std::size(buffer)));
    if (length > 0 && length < std::size(buffer)) {
        return std::filesystem::path{ buffer }.parent_path();
    }
#elif defined(__linux__)
    const std::filesystem::path self = std::filesystem::read_symlink("/proc/self/exe", ec);
    if (!ec) {
        return self.parent_path();
    }
#endif
    const std::filesystem::path from_argv = std::filesystem::absolute(argv0, ec);
    return ec ? std::filesystem::path{} : from_argv.parent_path();
}

#if defined(_WIN32)
// Started by double-click, the program owns a console nobody asked for. Drop it
// and send output to mp2.log in the settings folder instead; that file is what
// to attach to a bug report. Started from a terminal, nothing changes.
void redirect_output_if_double_clicked() {
    DWORD owners[2];
    if (GetConsoleWindow() == nullptr || GetConsoleProcessList(owners, 2) != 1) {
        return;
    }
    const std::filesystem::path log = mp2::settings_directory() / "mp2.log";
    std::error_code ec;
    std::filesystem::create_directories(log.parent_path(), ec);
    FILE* out = nullptr;
    if (freopen_s(&out, log.string().c_str(), "w", stdout) == 0) {
        _dup2(_fileno(stdout), _fileno(stderr));
    }
    else {
        freopen_s(&out, "NUL", "w", stdout);
    }
    FreeConsole();
    std::setvbuf(stdout, nullptr, _IONBF, 0);
    std::setvbuf(stderr, nullptr, _IONBF, 0);
}
#endif

}  // namespace

int main(int argc, char** argv) {
    std::setvbuf(stdout, nullptr, _IONBF, 0);

    // RecompFrontend opens assets/ relative to the working directory.
    {
        std::error_code ec;
        const std::filesystem::path exe_dir = executable_directory(argv[0]);
        if (!exe_dir.empty()) {
            std::filesystem::current_path(exe_dir, ec);
        }
    }

#if defined(_WIN32)
    redirect_output_if_double_clicked();
    timeBeginPeriod(1);
    SetConsoleOutputCP(CP_UTF8);
    // Sample queueing is unreliable with DirectSound (Zelda 64: Recompiled).
    SDL_setenv("SDL_AUDIODRIVER", "wasapi", 1);
#endif

    std::printf("%s %d.%d.%d\n", mp2::kProgramName, MP2_VERSION_MAJOR, MP2_VERSION_MINOR, MP2_VERSION_PATCH);

    {
        const std::filesystem::path settings = mp2::settings_directory();
        std::error_code ec;
        std::filesystem::create_directories(settings, ec);
        recomp::register_config_path(settings);
        std::printf("[mp2] settings: %s\n", settings.string().c_str());
    }

#if !MP2_ROM_HASH_KNOWN
    std::fprintf(stderr, "[mp2] warning: built without the ROM hash (python package 'xxhash' was missing);\n"
                         "      the launcher will not accept any ROM. Re-run the build script.\n");
#endif

    // The generated section tables reach librecomp before anything looks up an
    // address.
    mp2::register_overlays();

    recomp::GameEntry game{};
    game.rom_hash = MP2_ROM_HASH;
    game.internal_name = mp2::kInternalName;
    game.display_name = mp2::kDisplayName;
    game.game_id = mp2::kGameId;
    game.mod_game_id = mp2::kModGameId;
    // Mario Party 2 saves to a 4 Kbit EEPROM.
    game.save_type = recomp::SaveType::Eep4k;
    game.is_enabled = true;
    game.has_compressed_code = false;
    // Sign-extended: a zero-extended address would point 4 GB past RDRAM.
    game.entrypoint_address = static_cast<gpr>(static_cast<int32_t>(mp2::kEntrypoint));
    game.entrypoint = recomp_entrypoint;
    game.on_init_callback = mp2::on_runtime_init;

    if (!mp2::init_audio()) {
        return EXIT_FAILURE;
    }

    mp2::frontend::init(game);

    if (!recomp::register_game(game)) {
        std::fprintf(stderr, "[mp2] could not register the game with the runtime\n");
        return EXIT_FAILURE;
    }

    // A ROM path on the command line skips the launcher (handy for testing).
    bool start_now = false;
    if (argc >= 2 && argv[1][0] != '-') {
        const recomp::RomValidationError err = recomp::select_rom(std::filesystem::path{ argv[1] }, mp2::kGameId);
        if (err != recomp::RomValidationError::Good) {
            std::fprintf(stderr, "[mp2] the ROM was rejected (error %d); it must be Mario Party 2 (USA)\n",
                         static_cast<int>(err));
            return 2;
        }
        start_now = true;
    }

    const mp2::PlatformCallbacks platform = mp2::platform_callbacks();

    recomp::Configuration config{};
    config.argc = argc;
    config.argv = argv;
    config.project_version = recomp::Version{ MP2_VERSION_MAJOR, MP2_VERSION_MINOR, MP2_VERSION_PATCH };
    config.rsp_callbacks = platform.rsp;
    config.renderer_callbacks = mp2::frontend::renderer_callbacks();
    config.audio_callbacks = platform.audio;
    config.input_callbacks = platform.input;
    config.gfx_callbacks = platform.gfx;
    config.events_callbacks = platform.events;
    config.error_handling_callbacks = platform.error_handling;
    config.threads_callbacks = platform.threads;
    // Per event source: retry a message that finds its queue full, or drop it.
    // These are the runtime's own defaults, spelled out.
    config.message_queue_control = ultramodern::MessageQueueControl{};

    if (start_now) {
        recomp::start_game(mp2::kGameId, std::string{});
    }

    // Runs until the window is closed or Quit is chosen.
    recomp::start(config);

    mp2::frontend::shutdown();
    mp2::shutdown_platform();

#if defined(_WIN32)
    timeEndPeriod(1);
#endif
    return EXIT_SUCCESS;
}
