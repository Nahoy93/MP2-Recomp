#!/usr/bin/env python3
"""Write RecompiledFuncs/mp2_recomp_decls.h after N64Recomp has run.

N64Recomp emits calls to functions it does not translate itself:

  * libultra functions the runtime reimplements or ignores (renamed
    <name>_recomp), and
  * the functions listed under [patches] ignored in config/mp2.us.toml, which
    recomp/src implements natively.

Not all of those are declared in funcs.h, and C does not allow calling an
undeclared function, so this script declares every called-but-undeclared
function. Any <name>_recomp that neither the runtime nor recomp/src defines
gets a stub in mp2_recomp_stubs.cpp that logs once and returns 0, so a libultra
function the game references but never meaningfully uses cannot break the link.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

RECOMP_DIR = Path(__file__).resolve().parent.parent
CALL_RE = re.compile(r"(?<![\w)])([A-Za-z_]\w*)\(rdram, ctx\);")
DECL_RE = re.compile(r"void\s+([A-Za-z_]\w*)\s*\(\s*uint8_t\s*\*\s*rdram\s*,\s*recomp_context\s*\*\s*ctx\s*\)")
DEFN_RE = re.compile(r"\b([A-Za-z_]\w*)\s*\(\s*(?:uint8_t\s*\*\s*rdram|RDRAM_ARG)\s*(?:,|recomp_context)")
SKIP = {"LOOKUP_FUNC", "recomp_syscall_handler", "recomp_trigger_event"}


def defined_in(paths: list[Path]) -> set[str]:
    names: set[str] = set()
    for root in paths:
        if not root.exists():
            continue
        for path in root.rglob("*"):
            if path.suffix not in (".c", ".cpp", ".cc", ".h", ".hpp", ".inl"):
                continue
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            names.update(DEFN_RE.findall(text))
    return names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--funcs", type=Path, default=RECOMP_DIR / "generated" / "RecompiledFuncs")
    args = parser.parse_args()

    funcs_dir: Path = args.funcs
    funcs_h = funcs_dir / "funcs.h"
    if not funcs_h.exists():
        raise SystemExit(f"{funcs_h} saknas: kör N64Recomp först. / Run N64Recomp first.")

    declared = set(DECL_RE.findall(funcs_h.read_text(encoding="utf-8")))

    called: set[str] = set()
    for path in sorted(funcs_dir.glob("*.c")):
        called.update(CALL_RE.findall(path.read_text(encoding="utf-8", errors="replace")))
    called -= SKIP

    undeclared = sorted(called - declared)

    runtime = defined_in([RECOMP_DIR / "lib" / "N64ModernRuntime" / "librecomp",
                          RECOMP_DIR / "lib" / "N64ModernRuntime" / "ultramodern"])
    ours = defined_in([RECOMP_DIR / "src"])
    missing = [n for n in undeclared if n not in runtime and n not in ours]

    header = funcs_dir / "mp2_recomp_decls.h"
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by recomp/tools/gen_decls.py. Do not edit.\n")
        f.write("#pragma once\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        for name in undeclared:
            f.write(f"void {name}(uint8_t* rdram, recomp_context* ctx);\n")
        f.write("\n#ifdef __cplusplus\n}\n#endif\n")

    stubs = funcs_dir / "mp2_recomp_stubs.cpp"
    with open(stubs, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by recomp/tools/gen_decls.py. Do not edit.\n")
        f.write("// Functions the game calls that nothing implements. Each logs once.\n\n")
        f.write("#include <cstdio>\n#include \"recomp.h\"\n#include \"mp2_recomp_decls.h\"\n\n")
        for name in missing:
            f.write(
                f"extern \"C\" void {name}(uint8_t* rdram, recomp_context* ctx) {{\n"
                f"    (void)rdram;\n"
                f"    static bool reported = false;\n"
                f"    if (!reported) {{ reported = true; std::fprintf(stderr, \"[mp2] unimplemented: {name}\\n\"); }}\n"
                f"    ctx->r2 = 0;\n"
                f"}}\n\n")

    print(f"[gen_decls] {len(undeclared)} deklarationer, {len(missing)} stubbar"
          + (f": {', '.join(missing)}" if missing else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
